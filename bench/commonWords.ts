/**
 * Writes src/core/memory/commonWords.ts: the lower-case words of the bench corpora seen 3+ times, given
 * names (/usr/share/dict/propernames) and `KEEP` taken out. Run by hand: `node bench/commonWords.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod/mini';

const CORPORA = ['bench/recall-history.json', 'bench/recall-history-300.json', 'docs/measurements/2026-10-15-dogfood-m13.storyloom.json'];
/** Words also given names the dictionary list misses. */
const KEEP = ['rose'];
const MIN = 3;

const Story = z.object({ adventure: z.object({ actions: z.array(z.object({ versions: z.array(z.string()), active: z.number() })) }) });
const Cases = z.array(z.object({ output: z.string() }));
const read = (f: string): unknown => JSON.parse(readFileSync(f, 'utf8'));

const texts: string[] = [];
for (const f of CORPORA) for (const a of Story.parse(read(f)).adventure.actions) texts.push(a.versions[a.active] ?? '');
for (const c of Cases.parse(read('bench/contradiction-cases.json'))) texts.push(c.output);

const counts = new Map<string, number>();
for (const t of texts) for (const [w] of t.matchAll(/(?<![\p{L}'’])\p{Ll}+(?![\p{L}'’])/gu)) counts.set(w, (counts.get(w) ?? 0) + 1);
const names = new Set([
  ...readFileSync('/usr/share/dict/propernames', 'utf8')
    .split('\n')
    .map((n) => n.trim().toLowerCase()),
  ...KEEP,
]);
const words = [...counts]
  .filter(([w, n]) => n >= MIN && w.length > 1 && !names.has(w))
  .map(([w]) => w)
  .toSorted();

writeFileSync(
  'src/core/memory/commonWords.ts',
  `// Generated by bench/commonWords.ts; do not edit. ${words.length} words.\n` +
    `/** Lower-case words of the bench corpora seen ${MIN}+ times, given names removed. [provisional] */\n` +
    `export const COMMON_WORDS: ReadonlySet<string> = new Set(${JSON.stringify(words.join(' '))}.split(' '));\n`,
);
console.log(`${words.length} words`);
